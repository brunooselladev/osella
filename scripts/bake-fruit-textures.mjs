// Bakes the procedural textures of /fruit into public/fruit/tex/*.webp and writes
// components/fruit/baked.ts. Re-run after changing a generator in components/fruit/textures.ts.
//
//   pnpm dev            (in another terminal)
//   node scripts/bake-fruit-textures.mjs [http://localhost:3000]
//
// Needs `playwright-core` (npx -y -p playwright-core node scripts/bake-fruit-textures.mjs)
// and a Chromium-based browser; set BROWSER to its executable if it is not the default Edge.

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const base = process.argv[2] || 'http://localhost:3000'
const executablePath = process.env.BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'

const { chromium } = await import('playwright-core')
const browser = await chromium.launch({ executablePath, headless: true, args: ['--enable-gpu', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(`${base}/fruit?bake=1`, { waitUntil: 'networkidle' })
await page.waitForFunction(() => window.__bake && Object.keys(window.__bake).length > 10, null, { timeout: 60000 })
await page.waitForTimeout(3000)
const baked = await page.evaluate(() => window.__bake)
await browser.close()

const dir = join(root, 'public', 'fruit', 'tex')
await mkdir(dir, { recursive: true })
let bytes = 0
for (const [key, url] of Object.entries(baked)) {
  const buf = Buffer.from(url.split(',')[1], 'base64')
  bytes += buf.length
  await writeFile(join(dir, `${key}.webp`), buf)
}
const keys = Object.keys(baked).sort()
await writeFile(
  join(root, 'components', 'fruit', 'baked.ts'),
  `// Generated by scripts/bake-fruit-textures.mjs: textures served as /fruit/tex/<key>.webp\nexport const BAKED: string[] = ${JSON.stringify(keys, null, 2).replace(/"/g, "'")}\n`,
)
console.log(`baked ${keys.length} textures, ${(bytes / 1024).toFixed(0)} KB`)
